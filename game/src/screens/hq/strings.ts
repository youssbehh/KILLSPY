export type HqStringKey = keyof typeof HQ_STRINGS.fr;

export const useHqT = () => useLocalT<HqStringKey>(HQ_STRINGS);
export type HqT = ReturnType<typeof useHqT>;

export const GUILD_LIMITS = {
  nameMin: 3,
  nameMax: 24,
  tagMin: 2,
  tagMax: 5,
  descMax: 200,
  messageMax: 500,
} as const;

export const isValidGuildName = (name: string): boolean => {
  const length = name.trim().length;
  return length >= GUILD_LIMITS.nameMin && length <= GUILD_LIMITS.nameMax;
};

export const isValidGuildTag = (tag: string): boolean => /^[A-Za-z0-9]{2,5}$/.test(tag);
